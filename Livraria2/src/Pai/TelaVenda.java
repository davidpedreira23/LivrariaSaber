public void preencherTabela() {

    jTable1.getColumnModel().getColumn(0).setPreferredWidth(4);
    jTable1.getColumnModel().getColumn(1).setPreferredWidth(150);
    jTable1.getColumnModel().getColumn(2).setPreferredWidth(11);
    jTable1.getColumnModel().getColumn(3).setPreferredWidth(4);
    jTable1.getColumnModel().getColumn(4).setPreferredWidth(100);
    jTable1.getColumnModel().getColumn(5).setPreferredWidth(11);
    jTable1.getColumnModel().getColumn(6).setPreferredWidth(4);
    jTable1.getColumnModel().getColumn(7).setPreferredWidth(100);

    DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
    modelo.setNumRows(0);

    try {

        con_cliente.resultset.beforeFirst();

        while (con_cliente.resultset.next()) {

            modelo.addRow(new Object[]{
              con_cliente.resultset.getString("cod")
                    ,con_cliente.resultset.getString("titulo")
                    ,con_cliente.resultset.getString("preco")
                    ,con_cliente.resultset.getString("estoque")
                    , con_cliente.resultset.getString("editora")
                     ,con_cliente.resultset.getString("categoria")
                     ,con_cliente.resultset.getString("ISBN")
                    ,con_cliente.resultset.getString("Autor")
            });
        }

    } catch (SQLException erro) {
      JOptionPane.showMessageDialog(null,"\n Erro ao listar dados da tabela!! :\n "+erro,"Mensagem do Programa",JOptionPane.INFORMATION_MESSAGE);
        
    }
}
