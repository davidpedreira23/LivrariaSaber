    private void btnAdicionarCarrinhoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarCarrinhoActionPerformed
 int linhaSelecionada = jTable1.getSelectedRow();

    if (linhaSelecionada < 0) {
        JOptionPane.showMessageDialog(null, "Selecione um livro na tabela!");
        return;
    }

    try {
        int codLivro = Integer.parseInt(jTable1.getValueAt(linhaSelecionada, 0).toString());
        String tituloLivro = jTable1.getValueAt(linhaSelecionada, 1).toString();
        double preco = Double.parseDouble(jTable1.getValueAt(linhaSelecionada, 2).toString());
        int estoqueDisponivel = Integer.parseInt(jTable1.getValueAt(linhaSelecionada, 3).toString());
        int quantidade = Integer.parseInt(txtQuantidade.getText());

        if (quantidade <= 0) {
            JOptionPane.showMessageDialog(null, "Quantidade deve ser maior que zero!");
            return;
        }

        if (quantidade > estoqueDisponivel) {
            JOptionPane.showMessageDialog(null, "Estoque insuficiente! Disponível: " + estoqueDisponivel);
            return;
        }

        carrinho.add(new ItemCarrinho(codLivro, tituloLivro, preco, quantidade));
        atualizarTabelaCarrinho();
        txtQuantidade.setText("");

    } catch (NumberFormatException erro) {
        JOptionPane.showMessageDialog(null, "Digite uma quantidade válida!");
    }
    }//GEN-LAST:event_btnAdicionarCarrinhoActionPerformed

