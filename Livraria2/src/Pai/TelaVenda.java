private void atualizarTabelaCarrinho() {
    DefaultTableModel modeloCarrinho = (DefaultTableModel) jTableCarrinho.getModel();
    modeloCarrinho.setNumRows(0);

    double totalGeral = 0;

    for (ItemCarrinho item : carrinho) {
        modeloCarrinho.addRow(new Object[]{
            item.codLivro,
            item.titulo,
            item.quantidade,
            item.precoUnitario,
            item.getSubtotal()
        });
        totalGeral += item.getSubtotal();
    }

    IblTotal.setText(String.format("Total: R$ %.2f", totalGeral));
}


